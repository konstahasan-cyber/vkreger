BY_CODE = {p["code"]: p for p in PERSONAS}


def persona_for_index(index: int) -> dict[str, str]:
    return dict(PERSONAS[index % len(PERSONAS)])


def project_persona(project) -> dict[str, str] | None:  # noqa: ANN001
    persona = (project.brand or {}).get("persona")
    return persona if isinstance(persona, dict) and persona.get("voice") else None


def persona_block(project) -> str:  # noqa: ANN001
    persona = project_persona(project)
    if not persona:
        return ""
    lines = [
        f"Голос автора: {persona['voice']}",
        f"Структура постов: {persona['structure']}",
        f"Первая строка: {persona['opening']}",
        f"Длина: {persona['length']}; эмодзи: {persona['emoji']}.",
    ]
    if persona.get("focus"):
        lines.append(f"Фокус этой группы: {persona['focus']}")
    return "\n".join(lines)
